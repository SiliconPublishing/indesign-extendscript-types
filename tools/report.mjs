#!/usr/bin/env node
// Writes snapshots/<ver>/REPORT.md: what was measured, how much of the DOM it covers, and what the
// comparison found. Regenerate after `npm run dump` / `dump:runtime` / `dump:writes`.
//
//   node tools/report.mjs [--snapshot snapshots/indesign-21.6]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compare } from './compare/index.mjs';
import { compareLib } from './compare/lib.mjs';
import { SNAPSHOT } from './snapshot.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const i = process.argv.indexOf('--snapshot');
const snapshot = i >= 0 ? process.argv[i + 1] : SNAPSHOT;
const read = (f) => JSON.parse(readFileSync(join(root, snapshot, f), 'utf8'));

const dict = read('dictionary.json');
const classes = Object.values(dict.classes);
const enums = classes.filter((c) => c.kind === 'enum');
const collections = classes.filter((c) => c.kind !== 'enum' && c.methods.some((m) => m.name === 'everyItem'));
const objects = classes.filter((c) => c.kind !== 'enum' && !collections.includes(c));
const props = objects.reduce((n, c) => n + c.props.length, 0);
const writable = objects.reduce((n, c) => n + c.props.filter((p) => !p.readonly).length, 0);
const runtime = read('runtime.json');
const writes = existsSync(join(root, snapshot, 'writes.json')) ? read('writes.json') : { writes: {}, classesSampled: [] };
const crashers = existsSync(join(root, snapshot, 'runtime-crashers.json')) ? read('runtime-crashers.json') : {};
// Crashers carried over from desktop count only for classes this app has. Entries that are not
// reproduced (reproduced: false) are spots the samplers stay away from, not crashes of their own.
const ownClass = (k) => !!dict.classes[k.split(/[.[]/)[0]];
const crashing = Object.entries(crashers).filter(([k, v]) => v.reproduced !== false && ownClass(k));
const avoided = Object.entries(crashers).filter(([, v]) => v.reproduced === false);
const blockedClasses = new Set(avoided.filter(([k]) => /\.\*$/.test(k)).map(([k]) => k.split('.')[0]));
const sampledClasses = new Set(runtime.classesSampled);
const sampledObjects = objects.filter((c) => sampledClasses.has(c.name));
const readMembers = Object.keys(runtime.samples).length;
const writeMembers = Object.keys(writes.writes).length;
const allow = JSON.parse(readFileSync(join(root, 'tools/compare/allowlist.json'), 'utf8'));

const findings = ['desktop', 'server', 'portable'].flatMap((edition) => ['types', 'flat'].flatMap((tree) => compare({ edition, tree }).findings));
findings.push(...compareLib(), ...compareLib({ edition: 'server' }));
const unique = new Map(findings.map((f) => [`${f.kind}|${f.class}|${f.member}|${f.detail}`, f]));
const byKind = {};
for (const f of unique.values()) byKind[f.kind] = (byKind[f.kind] ?? 0) + 1;

const probes = readdirSync(join(root, 'test/probes')).filter((f) => f.endsWith('.jsx'));
// desktopProbe(...) runs on desktop only.
const probePattern = /server/.test(snapshot) ? /^\s*probe\(/gm : /^\s*(probe|desktopProbe)\(/gm;
const probeCount = probes.reduce((n, f) => n + (readFileSync(join(root, 'test/probes', f), 'utf8').match(probePattern) ?? []).length, 0);
const unsampled = objects.filter((c) => !sampledClasses.has(c.name)).map((c) => c.name);
// Why each remaining class has no runtime sample (tools/dump and test/probes notes).
const WHY = {
    Graphic: 'abstract superclass: InDesign reports the concrete class (Image, PDF, EPS, ...)',
    HiddenText: 'no method creates one',
    AssignedStory: 'no method adds a story to an assignment',
    PDFComment: 'importPdfComments needs a PDF exported from the document and annotated in Acrobat',
    Reply: 'as PDFComment',
    EPSText: 'the place gun does not load the EPS, and nothing else makes one',
    PagesPanel: 'app.panels report every panel as Panel; nothing is typed PagesPanel',
};

const pct = (a, b) => `${((100 * a) / b).toFixed(1)}%`;
const product = /server/.test(snapshot) ? 'InDesign Server' : 'InDesign';
const md = `# Measurement report: ${product} ${dict.version}

Generated by \`tools/report.mjs\` from \`${snapshot}/\`. Every number here is reproducible with
\`npm run dump\`, \`npm run dump:runtime\`, \`npm run dump:writes\` and \`npm test\`.

## Scripting dictionary (\`$.dictionary\`)

| | |
|---|---|
| Classes | ${classes.length} (${objects.length} objects, ${collections.length} collections, ${enums.length} enumerations) |
| Object properties | ${props} (${writable} writable) |
| Methods | ${classes.reduce((n, c) => n + c.methods.length, 0)} |
| Engine | ExtendScript ${read('corejs.json').version}, build ${dict.build} |

Every class, property, method, parameter and enumerator in the dictionary is compared with both
declaration trees (\`types/\`, \`flat/\`) on every \`npm test\`.

## Runtime measurements

| | covered | of |
|---|---|---|
| Object classes read at runtime | ${sampledObjects.length} (${pct(sampledObjects.length, objects.length)}) | ${objects.length} |
| Members read (class.property pairs) | ${readMembers} | |
| Writable members tried | ${writeMembers} | |
| Behaviour probes (test/probes) | ${probeCount} in ${probes.length} files | |
| Property reads/writes that crash InDesign | ${crashing.length} | |${avoided.length ? `\n| Classes or writes not sampled here (see below) | ${avoided.length} | |` : ''}

Reads and writes that crash InDesign (documented on the declarations; skipped by the samplers).
\`Class.prop\` is a read, \`Class.prop:trial\` a write of that kind of value, \`Class[]\` taking items
from such a collection, \`Class.*\` the class as a whole, \`Class.*:write\` every write to it:

${crashing.map(([k, v]) => `- \`${k}\` (${v.from ? `measured on InDesign desktop ${v.version}, not tried here` : `${product} ${v.version}`})`).join('\n') || '- none'}
${
    avoided.length
        ? `\nNot sampled here: ${avoided.map(([k]) => `\`${k}\``).join(', ')}. ${[...new Set(avoided.map(([, v]) => v.note))].join(' ')}`
        : ''
}

Object classes no fixture object reached, so checked against the dictionary only
(${unsampled.length}):

${unsampled.map((c) => `- \`${c}\`${WHY[c] ? `: ${WHY[c]}` : blockedClasses.has(c) ? ': not sampled here (above)' : ''}`).join('\n')}

## Findings (every edition)

${Object.entries(byKind)
    .sort((a, b) => b[1] - a[1])
    .map(([k, n]) => `- **${k}**: ${n}${allow.informational.includes(k) ? ' (informational)' : ''}`)
    .join('\n')}

Every finding that is not informational is explained by an entry in
\`tools/compare/allowlist.json\` (${allow.entries.length} entries, each with its reason and, where measured,
its probe); \`npm test\` fails on any other.
`;
writeFileSync(join(root, snapshot, 'REPORT.md'), md);
console.log(`wrote ${snapshot}/REPORT.md`);
